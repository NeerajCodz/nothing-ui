import { contrastRatio } from '@nothing-ui/core';
import { THEMES, type ThemeMode } from '@nothing-ui/tokens';

export interface CustomThemeConfig {
  mode: ThemeMode;
  accentHex: string;
  radiusPx: 0 | 8 | 16 | 24;
  density: 'compact' | 'standard' | 'airy';
  showDotField: boolean;
}

export const DEFAULT_CUSTOM_THEME: CustomThemeConfig = {
  mode: 'dark',
  accentHex: '#D71921',
  radiusPx: 16,
  density: 'standard',
  showDotField: true,
};

export const ACCENT_PRESETS = [
  { id: 'signal-red', label: 'Signal Red', hex: '#D71921' },
  { id: 'amber', label: 'Hardware Amber', hex: '#E07A16' },
  { id: 'emerald', label: 'Nominal Green', hex: '#16A34A' },
  { id: 'cobalt', label: 'Telemetry Blue', hex: '#2563EB' },
  { id: 'mono', label: 'Pure White', hex: '#FFFFFF' },
] as const;

export const RADIUS_PROFILES: ReadonlyArray<{ value: CustomThemeConfig['radiusPx']; label: string }> = [
  { value: 0, label: '0px Square' },
  { value: 8, label: '8px Technical' },
  { value: 16, label: '16px Hardware' },
  { value: 24, label: '24px Soft' },
];

export const DENSITY_PROFILES: ReadonlyArray<{ value: CustomThemeConfig['density']; label: string; pad: string }> = [
  { value: 'compact', label: 'Compact', pad: '12px' },
  { value: 'standard', label: 'Standard', pad: '16px' },
  { value: 'airy', label: 'Airy', pad: '24px' },
];

export function isValidHexColor(hex: string): boolean {
  return /^#[0-9A-Fa-f]{6}$/.test(hex.trim());
}

export function getAccentContrastReport(config: CustomThemeConfig): {
  onDarkBg: number;
  onLightBg: number;
  whiteOnAccent: number;
  blackOnAccent: number;
  recommendedFg: '#FFFFFF' | '#000000';
  meetsAAOnSurface: boolean;
} {
  const safeHex = isValidHexColor(config.accentHex) ? config.accentHex : '#D71921';
  const onDarkBg = Number(contrastRatio(safeHex, THEMES.dark.background).toFixed(2));
  const onLightBg = Number(contrastRatio(safeHex, THEMES.light.background).toFixed(2));
  const whiteOnAccent = Number(contrastRatio('#FFFFFF', safeHex).toFixed(2));
  const blackOnAccent = Number(contrastRatio('#000000', safeHex).toFixed(2));
  const recommendedFg = whiteOnAccent >= blackOnAccent ? '#FFFFFF' : '#000000';
  const surfaceBg = THEMES[config.mode].surface;
  const meetsAAOnSurface = contrastRatio(safeHex, surfaceBg) >= 3.0;

  return {
    onDarkBg,
    onLightBg,
    whiteOnAccent,
    blackOnAccent,
    recommendedFg,
    meetsAAOnSurface,
  };
}

export function generateCustomThemeCss(config: CustomThemeConfig): string {
  const accent = isValidHexColor(config.accentHex) ? config.accentHex.toUpperCase() : '#D71921';
  const pad = DENSITY_PROFILES.find((d) => d.value === config.density)?.pad ?? '16px';
  const dotOpacity = config.showDotField ? '0.28' : '0';

  return `/* Generated by Nothing UI Theme Customizer (package: nthgui) */
@import "tailwindcss";

@theme {
  --color-nothing-accent: ${accent};
  --radius-nothing-card: ${config.radiusPx}px;
  --radius-nothing-control: ${Math.max(0, Math.round(config.radiusPx * 0.5))}px;
  --spacing-nothing-panel: ${pad};
}

:root,
[data-theme="${config.mode}"] {
  --nt-bg: ${THEMES[config.mode].background};
  --nt-surface: ${THEMES[config.mode].surface};
  --nt-raised: ${THEMES[config.mode].surfaceRaised};
  --nt-line: ${THEMES[config.mode].border};
  --nt-line-2: ${THEMES[config.mode].borderStrong};
  --nt-display: ${THEMES[config.mode].foreground};
  --nt-secondary: ${THEMES[config.mode].foregroundSecondary};
  --nt-muted: ${THEMES[config.mode].foregroundMuted};
  --nt-accent: ${accent};
  --nt-radius-card: ${config.radiusPx}px;
  --nt-panel-padding: ${pad};
  --nt-dot-field-opacity: ${dotOpacity};
}
`;
}

export function generateCustomTokensJson(config: CustomThemeConfig): string {
  const accent = isValidHexColor(config.accentHex) ? config.accentHex.toUpperCase() : '#D71921';
  return JSON.stringify(
    {
      package: 'nthgui',
      mode: config.mode,
      accent,
      radiusPx: config.radiusPx,
      density: config.density,
      showDotField: config.showDotField,
      palette: THEMES[config.mode],
    },
    null,
    2,
  );
}
