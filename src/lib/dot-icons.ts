export type DotIconName = keyof typeof DOT_ICON_BITMAPS;

export const DOT_ICON_NAMES = Object.keys(DOT_ICON_BITMAPS) as DotIconName[];

export interface DotPoint {
  x: number;
  y: number;
}

export function getDotIconPoints(name: DotIconName): DotPoint[] {
  const rows = DOT_ICON_BITMAPS[name];
  const points: DotPoint[] = [];
  for (let y = 0; y < rows.length; y++) {
    const row = rows[y];
    for (let x = 0; x < row.length; x++) {
      if (row[x] === '#') {
        points.push({ x, y });
      }
    }
  }
  return points;
}

export function buildDotIconUsageSnippet(name: DotIconName, size: number): string {
  return `import { DotIcon } from "@/components/nothing/DotIcon"\n\nexport function Example() {\n  return <DotIcon name="${name}" size={${size}} />\n}`;
}
